let current = 0;

let answers = Array(25).fill(null);


/* =========================
   页面
========================= */

function startTest() {

    current = 0;

    answers = Array(25).fill(null);

    show("quizPage");

    render();
}


function show(id) {

    document
        .querySelectorAll(".page")
        .forEach(page => {
            page.classList.remove("active");
        });

    document
        .getElementById(id)
        .classList.add("active");

    window.scrollTo(0, 0);
}


/* =========================
   渲染题目
========================= */

function render() {

    const q = questions[current];

    document.getElementById("questionNumber")
        .textContent =
        String(current + 1).padStart(2, "0")
        + " / 25";


    document.getElementById("progressBar")
        .style.width =
        ((current + 1) / 25 * 100) + "%";


    document.getElementById("dimensionName")
        .textContent =
        q[0] + " · " + q[1];


    document.getElementById("questionText")
        .textContent =
        q[2];


    const box =
        document.getElementById("options");

    box.innerHTML = "";


    q[3].forEach((text, i) => {

        const option =
            document.createElement("div");

        option.className =
            "option"
            +
            (
                answers[current] === i
                    ? " selected"
                    : ""
            );


        option.innerHTML = `

            <div class="option-letter">
                ${"ABCD"[i]}
            </div>

            <div class="option-text">
                ${text}
            </div>

        `;


        option.onclick = () => {

            answer(i);

        };


        box.appendChild(option);

    });


    document.getElementById("prevBtn")
        .style.visibility =
        current
            ? "visible"
            : "hidden";


    document.getElementById("selectionHint")
        .textContent =
        answers[current] === null
            ? "请选择一个答案"
            : "已选择";
}


/* =========================
   选择答案
========================= */

function answer(i) {

    answers[current] = i;

    render();


    setTimeout(() => {

        if (current < 24) {

            current++;

            render();

        } else {

            result();

        }

    }, 180);
}


function previousQuestion() {

    if (current > 0) {

        current--;

        render();

    }

}


/* =========================
   计算结果
========================= */

function result() {

    const scores = {

        W: 0,
        D: 0,

        C: 0,
        M: 0,

        E: 0,
        I: 0,

        P: 0,
        A: 0,

        R: 0,
        S: 0

    };


    const pairs = [

        ["W", "D"],
        ["C", "M"],
        ["E", "I"],
        ["P", "A"],
        ["R", "S"]

    ];


    answers.forEach((answer, index) => {

        const pair =
            pairs[Math.floor(index / 5)];


        if (answer < 2) {

            scores[pair[0]] +=
                answer === 0
                    ? 2
                    : 1;

        } else {

            scores[pair[1]] +=
                answer === 3
                    ? 2
                    : 1;

        }

    });


    const code =
        pairs
            .map(pair => {

                return scores[pair[0]]
                    >= scores[pair[1]]
                    ? pair[0]
                    : pair[1];

            })
            .join("");


    renderResult(
        code,
        scores
    );


    show("resultPage");
}


